"""
logmap_llm.oracle.prompts.context

The immutable per-run prompt context, replacing four mutable module-level globals.

WHAT THIS REPLACED

`templates.py` held `_answer_format` / `_response_mode` / `_response_instruction`,
`_ontology_domain` and `_global_fmt_fn` as module state, mutated from `pipeline/stage_two.py`,
`oracle/rag/bundle.py` and `pipeline/mediation.py`. Every one of ~33 template functions read
them implicitly, so what a template rendered depended on whatever had last called a setter.
`stage_two.py` said as much in a comment: *"this may not be the best of ideas, since we're
modifying global state ... this subprocess should have its own dedicated `global
_ontology_domain`, just be careful when modifying this later"*.

Process isolation contained it in normal CLI use — one subprocess, one config, one setter
call. In-process or concurrent use did not: two runs in one interpreter share the state, and
the failure mode is not a crash but *prompts rendered under the wrong response instruction or
the wrong domain*, which no test would catch and no artefact would record.

WHAT IT IS NOW

A frozen dataclass, constructed once per run and passed explicitly to every template. Nothing
mutates; a different context is a different object.

BYTE EQUIVALENCE IS THE POINT

The derived accessors below reproduce the old module functions character for character,
including the single-space fallback in `forced_domain_string`. `tests/goldens/prompt_templates.json`
was generated by the pre-refactor code and pins all 38 registered templates across both
domain settings and all four (answer_format, response_mode) combinations. If this file is
wrong, that test fails — which is the only reason the refactor is safe to make in the same
pass as a change to negative construction.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

from logmap_llm.constants import (
    ANSWER_FORMATS,
    DEFAULT_ANSWER_FORMAT,
    DEFAULT_RESPONSE_MODE,
    RESPONSE_INSTRUCTION,
    RESPONSE_MODES,
)
from logmap_llm.oracle.prompts.formatting import format_instance_attribute_clause


@dataclass(frozen=True)
class PromptContext:
    """Everything a prompt template needs beyond the two entities it is rendering."""

    answer_format: str = DEFAULT_ANSWER_FORMAT
    response_mode: str = DEFAULT_RESPONSE_MODE
    ontology_domain: str | None = None
    #: Formats one instance attribute clause. Only the instance templates consult it, and
    #: only when the caller has not passed an explicit `fmt_fn`.
    instance_fmt_fn: Callable = format_instance_attribute_clause

    def __post_init__(self) -> None:
        if self.answer_format not in ANSWER_FORMATS:
            raise ValueError(
                f"Unknown answer_format '{self.answer_format}'. "
                f"Valid options: {sorted(ANSWER_FORMATS)}"
            )
        if self.response_mode not in RESPONSE_MODES:
            raise ValueError(
                f"Unknown response_mode '{self.response_mode}'. "
                f"Valid options: {sorted(RESPONSE_MODES)}"
            )

    @classmethod
    def from_config(cls, config, *, instance_fmt_fn: Callable | None = None) -> "PromptContext":
        """Build the context for one run from its validated LogMapLLMConfig.

        The two response fields are passed through UNCONVERTED. `AnswerFormat` and
        `ResponseModes` are `(str, Enum)` members, so they compare and hash equal to their
        values and satisfy both the `ANSWER_FORMATS`/`RESPONSE_MODES` membership checks and
        the `RESPONSE_INSTRUCTION` tuple lookup. `str()` on such a member returns
        `'AnswerFormat.TRUE_FALSE'`, NOT `'true_false'` — coercing here made
        `__post_init__` reject every valid config, which is what the pre-refactor
        `set_response_config(config.oracle.answer_format, config.oracle.response_mode)`
        never did because it passed the members straight through. See
        tests/test_prompt_context_from_config.py.
        """
        return cls(
            answer_format=config.oracle.answer_format,
            response_mode=config.oracle.response_mode,
            ontology_domain=config.alignmentTask.ontology_domain,
            instance_fmt_fn=instance_fmt_fn or format_instance_attribute_clause,
        )

    # --- derived, byte-identical to the module functions they replace ------

    @property
    def response_instruction(self) -> str:
        """The instruction appended to a prompt; depends on the (format, mode) PAIR."""
        return RESPONSE_INSTRUCTION[(self.answer_format, self.response_mode)]

    @property
    def domain_preamble(self) -> str:
        if self.ontology_domain:
            return f"We have two entities from different {self.ontology_domain} ontologies."
        return "We have two entities from different ontologies."

    @property
    def forced_domain_string(self) -> str:
        """A space-padded domain qualifier, or a single space.

        Some legacy prompts hard-code a domain qualifier ("two <domain> ontologies") and differ
        from the expected domain preamble. For those the domain string is "forced", even if none
        has been set, so the surrounding spacing stays correct.
        """
        if self.ontology_domain:
            return str(f" {self.ontology_domain} ")
        return " "
